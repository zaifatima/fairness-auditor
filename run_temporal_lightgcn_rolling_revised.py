def build_config(dataset_name: str) -> Config:
    if not MAIN_CONFIG_FILE.exists():
        raise FileNotFoundError(
            f"Main LightGCN config not found:\n"
            f"{MAIN_CONFIG_FILE}"
        )

    # Read the existing main LightGCN configuration and override
    # only the settings needed for this temporal experiment.
    config_dict = {
        "dataset": dataset_name,
        "data_path": str(TEMPORAL_DATASET_ROOT),

        "model": "LightGCN",

        "device": DEVICE,

        "n_layers": N_LAYERS,
        "embedding_size": EMBEDDING_SIZE,
        "reg_weight": REG_WEIGHT,

        "epochs": EPOCHS,
        "train_batch_size": TRAIN_BATCH_SIZE,
        "eval_batch_size": TRAIN_BATCH_SIZE,
        "learning_rate": LEARNING_RATE,

        "min_user_inter_num": MIN_USER_INTERACTIONS,
        "min_item_inter_num": MIN_ITEM_INTERACTIONS,

        # Required by the RecBole Dataset/LightGCN configuration.
        # We do NOT call data_preparation() and therefore do NOT
        # use this setting to create a validation/test split.
        "eval_args": {
            "split": {
                "RS": [
                    0.8,
                    0.1,
                    0.1,
                ]
            },
            "group_by": "user",
            "order": "RO",
            "mode": {
                "valid": "uni100",
                "test": "uni100",
            },
        },

        "seed": SEED,
    }

    config = Config(
        model="LightGCN",
        dataset=dataset_name,
        config_file_list=[str(MAIN_CONFIG_FILE)],
        config_dict=config_dict,
    )

    return config


# ============================================================
# MANUAL BPR TRAINING
# ============================================================

def build_positive_sets(
    user_ids: np.ndarray,
    item_ids: np.ndarray,
) -> dict[int, set[int]]:

    positives: dict[int, set[int]] = {}

    for user_id, item_id in zip(
        user_ids,
        item_ids,
    ):
        user_id = int(user_id)
        item_id = int(item_id)

        if user_id not in positives:
            positives[user_id] = set()

        positives[user_id].add(item_id)

    return positives


def sample_negative_items(
    users: np.ndarray,
    item_count: int,
    positive_sets: dict[int, set[int]],
    rng: np.random.Generator,
) -> np.ndarray:

    negatives = rng.integers(
        low=0,
        high=item_count,
        size=len(users),
        dtype=np.int64,
    )

    # Re-sample collisions with each user's historical positives.
    for idx, raw_user in enumerate(users):
        user = int(raw_user)
        positives = positive_sets.get(user, set())

        while int(negatives[idx]) in positives:
            negatives[idx] = rng.integers(
                low=0,
                high=item_count,
            )

    return negatives


def train_temporal_model(
    config: Config,
    evaluation_year: int,
    dataset,
) -> tuple[LightGCN, list[float], float]:

    print()
    print("=" * 70)
    print(
        f"Training LightGCN for {evaluation_year}"
    )
    print("=" * 70)
    print(
        "Training mode: historical data only"
    )
    print(
        "Validation: disabled"
    )
    print(
        f"Epochs: {EPOCHS}"
    )
    print(
        f"Train batch size: {TRAIN_BATCH_SIZE:,}"
    )
    print(
        f"Layers: {N_LAYERS}"
    )

    model = LightGCN(
        config,
        dataset,
    ).to(config["device"])

    optimizer = torch.optim.Adam(
        model.parameters(),
        lr=LEARNING_RATE,
    )

    uid_field = dataset.uid_field
    iid_field = dataset.iid_field

    users = (
        dataset.inter_feat[uid_field]
        .cpu()
        .numpy()
        .astype(np.int64)
    )

    items = (
        dataset.inter_feat[iid_field]
        .cpu()
        .numpy()
        .astype(np.int64)
    )

    positive_sets = build_positive_sets(
        users,
        items,
    )

    rng = np.random.default_rng(SEED)

    n_examples = len(users)
    order = np.arange(n_examples)

    epoch_losses: list[float] = []

    start_time = time.time()

    for epoch in range(EPOCHS):
        epoch_start = time.time()

        rng.shuffle(order)

        total_loss = 0.0
        total_examples = 0

        model.train()

        for start in range(
            0,
            n_examples,
            TRAIN_BATCH_SIZE,
        ):
            batch_idx = order[
                start:start + TRAIN_BATCH_SIZE
            ]

            batch_users = users[batch_idx]
            batch_pos = items[batch_idx]

            batch_neg = sample_negative_items(
                batch_users,
                dataset.item_num,
                positive_sets,
                rng,
            )

            user_tensor = torch.from_numpy(
                batch_users
            ).to(config["device"])

            pos_tensor = torch.from_numpy(
                batch_pos
            ).to(config["device"])

            neg_tensor = torch.from_numpy(
                batch_neg
            ).to(config["device"])

            optimizer.zero_grad()

            user_all, item_all = model.forward()

            user_emb = user_all[user_tensor]
            pos_emb = item_all[pos_tensor]
            neg_emb = item_all[neg_tensor]

            pos_scores = (
                user_emb * pos_emb
            ).sum(dim=1)

            neg_scores = (
                user_emb * neg_emb
            ).sum(dim=1)

            mf_loss = model.mf_loss(
                pos_scores,
                neg_scores,
            )

            u_ego = model.user_embedding(
                user_tensor
            )

            pos_ego = model.item_embedding(
                pos_tensor
            )

            neg_ego = model.item_embedding(
                neg_tensor
            )

            reg_loss = model.reg_loss(
                u_ego,
                pos_ego,
                neg_ego,
                require_pow=config["require_pow"],
            )

            loss = (
                mf_loss
                + REG_WEIGHT * reg_loss
            )

            loss.backward()
            optimizer.step()

            batch_size = len(batch_idx)

            total_loss += (
                float(loss.detach().cpu())
                * batch_size
            )
            total_examples += batch_size

        epoch_loss = (
            total_loss / max(total_examples, 1)
        )

        epoch_losses.append(epoch_loss)

        print(
            f"Epoch {epoch + 1}/{EPOCHS} | "
            f"loss={epoch_loss:.6f} | "
            f"time={(time.time() - epoch_start) / 60:.2f} min"
        )

    training_minutes = (
        time.time() - start_time
    ) / 60.0

    print()
    print(
        f"Training complete for {evaluation_year}"
    )
    print(
        f"Training time: "
        f"{training_minutes:.2f} minutes"
    )

    return (
        model,
        epoch_losses,
        training_minutes,
    )


