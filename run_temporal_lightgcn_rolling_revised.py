def prepare_recbole_dataset(
    historical_df: pd.DataFrame,
    evaluation_year: int,
) -> tuple[str, Path]:

    dataset_name = (
        f"ml32m_temporal_lightgcn_{evaluation_year}"
    )

    dataset_dir = (
        TEMPORAL_DATASET_ROOT / dataset_name
    )

    dataset_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    inter_file = (
        dataset_dir
        / f"{dataset_name}.inter"
    )

    # Historical data only.
    output = historical_df[
        [
            "user_id",
            "item_id",
            "rating",
            "timestamp",
        ]
    ].copy()

    output["user_id"] = (
        output["user_id"].astype(str)
    )

    output["item_id"] = (
        output["item_id"].astype(str)
    )

    output["timestamp"] = (
        output["timestamp"].astype(np.int64)
    )

    output = output.rename(
        columns={
            "user_id": "user_id:token",
            "item_id": "item_id:token",
            "rating": "rating:float",
            "timestamp": "timestamp:float",
        }
    )

    if not inter_file.exists():
        print(
            f"Writing historical RecBole file:\n"
            f"{inter_file}"
        )

        output.to_csv(
            inter_file,
            sep="\t",
            index=False,
        )
    else:
        print(
            f"Using existing historical RecBole file:\n"
            f"{inter_file}"
        )

    return dataset_name, dataset_dir


