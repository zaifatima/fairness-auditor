def main() -> None:
    ensure_directories()
    set_reproducibility()

    print()
    print("=" * 70)
    print("ROLLING TEMPORAL LIGHTGCN — REVISED")
    print("=" * 70)
    print(
        f"Evaluation years: {EVALUATION_YEARS}"
    )
    print(
        f"Historical start: "
        f"{HISTORICAL_START_YEAR}"
    )
    print(
        f"Epochs per checkpoint: {EPOCHS}"
    )
    print(
        f"Training batch size: "
        f"{TRAIN_BATCH_SIZE:,}"
    )
    print(
        f"LightGCN layers: {N_LAYERS}"
    )
    print(
        "Internal validation: DISABLED"
    )
    print(
        "Temporal cadence: every 2 years"
    )
    print("=" * 70)

    full_df = load_input()

    summaries = []

    for evaluation_year in EVALUATION_YEARS:
        try:
            result = run_one_year(
                full_df,
                evaluation_year,
            )
            summaries.append(result)

        except KeyboardInterrupt:
            print()
            print(
                "Interrupted by user. "
                "Completed years remain saved."
            )
            raise

        except Exception as exc:
            print()
            print(
                f"ERROR in year {evaluation_year}: "
                f"{exc}"
            )

            error_row = {
                "year": evaluation_year,
                "status": "error",
                "error": str(exc),
            }

            summaries.append(error_row)
            append_log(error_row)

    final_summary_file = (
        SUMMARY_DIR
        / "LightGCN-temporal-run-summary.json"
    )

    with open(
        final_summary_file,
        "w",
        encoding="utf-8",
    ) as handle:
        json.dump(
            summaries,
            handle,
            indent=2,
            default=str,
        )

    print()
    print("=" * 70)
    print(
        "ROLLING TEMPORAL LIGHTGCN COMPLETE"
    )
    print("=" * 70)
    print(
        f"Summary:\n{final_summary_file}"
    )


if __name__ == "__main__":
    main()
