def load_input() -> pd.DataFrame:
    if not INPUT_FILE.exists():
        raise FileNotFoundError(
            f"Input file not found:\n{INPUT_FILE}"
        )

    print("=" * 70)
    print("Loading main 50k interaction dataset")
    print("=" * 70)

    df = pd.read_csv(
        INPUT_FILE,
        sep="\t",
        usecols=[
            "user_id:token",
            "item_id:token",
            "rating:float",
            "timestamp:float",
        ],
    )

    df = df.rename(
        columns={
            "user_id:token": "user_id",
            "item_id:token": "item_id",
            "rating:float": "rating",
            "timestamp:float": "timestamp",
        }
    )

    df["user_id"] = pd.to_numeric(
        df["user_id"], errors="raise"
    ).astype(np.int64)

    df["item_id"] = pd.to_numeric(
        df["item_id"], errors="raise"
    ).astype(np.int64)

    df["rating"] = pd.to_numeric(
        df["rating"], errors="raise"
    ).astype(np.float32)

    df["timestamp"] = pd.to_numeric(
        df["timestamp"], errors="raise"
    ).astype(np.int64)

    df["year"] = pd.to_datetime(
        df["timestamp"],
        unit="s",
        errors="coerce",
    ).dt.year.astype("Int64")

    df = df[df["year"].notna()].copy()
    df["year"] = df["year"].astype(np.int16)

    df = df[
        df["year"] >= HISTORICAL_START_YEAR
    ].copy()

    print(f"Rows loaded: {len(df):,}")
    print(f"Users: {df['user_id'].nunique():,}")
    print(f"Items: {df['item_id'].nunique():,}")
    print(
        f"Years retained: "
        f"{df['year'].min()}-{df['year'].max()}"
    )

    return df


