#!/usr/bin/env python3
"""
Rolling temporal LightGCN experiment for the fairness auditor.

Design:
    For evaluation year T:
        1. Build historical data using years < T.
        2. Train LightGCN ONLY on that historical data.
        3. Do NOT create an internal train/validation/test split.
        4. Do NOT run RecBole validation during training.
        5. Save a year-specific checkpoint.
        6. Generate Top-10 recommendations for users who have
           historical activity and an interaction in year T.
        7. Repeat at a two-year cadence.

This is a temporal drift/fairness experiment, not a hyperparameter-
tuning experiment. The actual evaluation-year interactions remain
outside the training data.

The model architecture/batch settings remain aligned with the main
LightGCN configuration:
    n_layers = 1
    train_batch_size = 16384
    learning_rate = 0.001

Temporal training is intentionally reduced to 3 epochs because the
objective is to generate consistent historical snapshots for fairness
analysis rather than optimise recommendation accuracy at every year.

The old 2001 temporal run should NOT be treated as part of the final
comparable series if it was generated by the previous implementation.
"""

