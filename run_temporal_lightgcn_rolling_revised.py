def build_year_data(
    full_df: pd.DataFrame,
    evaluation_year: int,
) -> tuple[pd.DataFrame, pd.DataFrame]:

    historical_df = full_df[
        full_df["year"] < evaluation_year
    ].copy()

    test_df = full_df[
        full_df["year"] == evaluation_year
    ].copy()

    if historical_df.empty:
        raise ValueError(
            f"No historical data available before "
            f"{evaluation_year}."
        )

    if test_df.empty:
        raise ValueError(
            f"No evaluation data found for "
            f"{evaluation_year}."
        )

    print()
    print("-" * 70)
    print(f"Temporal split: evaluation year {evaluation_year}")
    print("-" * 70)
    print(
        f"Historical period: "
        f"{historical_df['year'].min()}-"
        f"{historical_df['year'].max()}"
    )
    print(
        f"Historical rows: {len(historical_df):,}"
    )
    print(
        f"Historical users: "
        f"{historical_df['user_id'].nunique():,}"
    )
    print(
        f"Historical items: "
        f"{historical_df['item_id'].nunique():,}"
    )
    print(
        f"Evaluation rows: {len(test_df):,}"
    )
    print(
        f"Evaluation users: "
        f"{test_df['user_id'].nunique():,}"
    )

    return historical_df, test_df


