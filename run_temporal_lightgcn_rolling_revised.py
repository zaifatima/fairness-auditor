def save_checkpoint(
    model: LightGCN,
    config: Config,
    evaluation_year: int,
    epoch_losses: list[float],
) -> Path:

    checkpoint_file = (
        CHECKPOINT_DIR
        / f"LightGCN-temporal-{evaluation_year}.pth"
    )

    torch.save(
        {
            "model": "LightGCN",
            "evaluation_year": evaluation_year,
            "state_dict": model.state_dict(),
            "config": dict(
                config.final_config_dict
            ),
            "epoch_losses": epoch_losses,
        },
        checkpoint_file,
    )

    print(
        f"Checkpoint saved:\n"
        f"{checkpoint_file}"
    )

    return checkpoint_file


